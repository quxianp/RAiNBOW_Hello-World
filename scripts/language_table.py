#!/usr/bin/env python3
"""Generate the index of every language file, with what each one contains.

Seven thousand three hundred and twenty-six files is not a navigable number. The
manifest lists them, but the manifest is a JSON blob meant for a program, and the
language bar is a picture of 631 coloured slivers. Neither answers "what is in
this repository and is it any good", and that is the question a visitor arrives
with.

This writes `data/LANGUAGES.md`: every file, grouped by kind, with its extension,
its path, and whether it carries a program. It is a generated artefact and it is
regenerated whenever the templates change, so it cannot describe a repository
that no longer exists.

    python scripts/language_table.py                 # write data/LANGUAGES.md
    python scripts/language_table.py --check         # fail if it is stale
    python scripts/language_table.py --kind esolang  # just one section
"""

from __future__ import annotations

import argparse
import importlib.util
import json
import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
MANIFEST = ROOT / "hello" / "manifest.json"
GEN = ROOT / "scripts" / "generate_all_hello.py"
CLASSES = ROOT / "data" / "placeholder_classes.json"
OUT = ROOT / "data" / "LANGUAGES.md"

SECTION_ORDER = ["programming", "esolang", "document", "binary", "index"]
SECTION_TITLES = {
    "programming": "Carrying a program",
    "esolang": "Esoteric languages with no canonical Hello World",
    "document": "Documents and data formats, where the content is the answer",
    "binary": "Binary formats: a magic number and where the greeting would go",
    "index": "Index entries that are not languages",
}


def load_generator():
    spec = importlib.util.spec_from_file_location("gen", GEN)
    mod = importlib.util.module_from_spec(spec)
    sys.modules["gen"] = mod
    spec.loader.exec_module(mod)
    return mod


def classify(name: str, gen) -> str:
    key = (name or "").strip().lower()
    templates = getattr(gen, "HELLO", {})
    inherit = getattr(gen, "INHERIT", {})
    if templates.get(key, "").strip() or key in inherit:
        return "programming"

    if CLASSES.exists():
        data = json.loads(CLASSES.read_text(encoding="utf-8"))
        for rec in data["files"]:
            if (rec.get("language") or "").lower() == key:
                kind = rec.get("kind")
                return {
                    "program": "programming",   # no program yet, but it is one
                    "esolang": "esolang",
                    "document": "document",
                    "binary": "binary",
                }.get(kind, "index")
    return "index"


def build(kinds: list[str] | None = None) -> str:
    gen = load_generator()
    man = json.loads(MANIFEST.read_text(encoding="utf-8"))

    buckets: dict[str, list[tuple[str, str, str]]] = {k: [] for k in SECTION_ORDER}
    for f in man["files"]:
        kind = classify(f["language"], gen)
        buckets[kind].append((
            f["language"],
            f.get("extension") or "-",
            f["path"],
        ))

    out = [
        "# Every language file in this repository",
        "",
        "<!-- GENERATED by scripts/language_table.py. Do not edit by hand. -->",
        "",
        "Seven thousand three hundred and twenty-six files, grouped by what",
        "they actually contain rather than by where they sit. The point of the",
        "grouping is that \"no Hello World\" is not one fact about this",
        "repository but four, and only one of them is unfinished work.",
        "",
        "| section | files |",
        "|---|---:|",
    ]
    for kind in SECTION_ORDER:
        if kinds and kind not in kinds:
            continue
        out.append(f"| {SECTION_TITLES[kind]} | {len(buckets[kind]):,} |")
    out.append(f"| **total** | **{len(man['files']):,}** |")
    out.append("")

    for kind in SECTION_ORDER:
        if kinds and kind not in kinds:
            continue
        rows = sorted(buckets[kind], key=lambda r: (r[1], r[0]))
        out.append(f"## {SECTION_TITLES[kind]} ({len(rows):,})")
        out.append("")
        out.append("| language | extension | file |")
        out.append("|---|---|---|")
        for lang, ext, path in rows:
            out.append(f"| {lang} | `{ext}` | `{path}` |")
        out.append("")

    return "\n".join(out)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--check", action="store_true",
                    help="exit 1 if data/LANGUAGES.md is out of date")
    ap.add_argument("--kind", action="append",
                    help="only this section (repeatable)")
    ap.add_argument("--stdout", action="store_true")
    args = ap.parse_args()

    text = build(args.kind)

    # `--kind` filters the *output on screen* only. The first version of this
    # applied the filter to the written file too, so asking for one section
    # overwrote a 7 368-line index with a 27-line one. A generated artefact that
    # can be silently truncated is worse than none.
    if args.kind and not args.stdout:
        print("note: --kind only affects --stdout; writing every section")
        text = build(None)

    if args.stdout:
        print(text)
        return 0

    if args.check:
        if not OUT.exists():
            print(f"check: {OUT} does not exist", file=sys.stderr)
            return 1
        if OUT.read_text(encoding="utf-8") != text:
            print(f"check: {OUT.name} is stale; run without --check",
                  file=sys.stderr)
            return 1
        print(f"check: {OUT.name} is current")
        return 0

    OUT.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.relative_to(ROOT)}  "
          f"({len(text.splitlines()):,} lines, {OUT.stat().st_size:,} bytes)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
