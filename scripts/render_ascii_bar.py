#!/usr/bin/env python3
"""Render the 694 core languages as terminal ASCII art, in hue order.

    python scripts/render_ascii_bar.py
    python scripts/render_ascii_bar.py --width 100 --out assets/ascii-bar.txt

The point is that this needs no image viewer, no browser and no network. Open
the file in any terminal and the rainbow is right there, one character per
language, arranged by the hue of its Linguist colour.

Characters are picked so adjacent languages do not read as one run: the set is
cycled rather than assigned by position, and the hue order is stable because it
comes from the same config/rainbow_langs.json that orders the bar itself.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
CONFIG = ROOT / "config" / "rainbow_langs.json"
OUT = ROOT / "assets" / "ascii-bar.txt"

# Deliberately high-contrast glyphs. A single character repeated across 694
# columns reads as a smear; cycling a small set keeps the segments legible.
GLYPHS = "█▓▒░#@%&*+=-~:."


def hue_to_rgb(h: float, s: float, v: float) -> tuple[int, int, int]:
    """HSV to RGB, matching the sweep used by generate_rainbow_bar.py."""
    h = h % 360.0
    c = v * s
    x = c * (1 - abs((h / 60.0) % 2 - 1))
    m = v - c
    if h < 60:
        rgb = (c, x, 0.0)
    elif h < 120:
        rgb = (x, c, 0.0)
    elif h < 180:
        rgb = (0.0, c, x)
    elif h < 240:
        rgb = (0.0, x, c)
    elif h < 300:
        rgb = (x, 0.0, c)
    else:
        rgb = (c, 0.0, x)
    return tuple(int(round(v * 255)) for v in rgb)


def hex_to_rgb(value: str) -> tuple[int, int, int] | None:
    if not value:
        return None
    v = value.lstrip("#")
    if len(v) != 6:
        return None
    try:
        return (int(v[0:2], 16), int(v[2:4], 16), int(v[4:6], 16))
    except ValueError:
        return None


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--width", type=int, default=96,
                    help="characters per row (default 96)")
    ap.add_argument("--out", default=str(OUT))
    args = ap.parse_args()

    if not CONFIG.is_file():
        print(f"error: {CONFIG} missing", file=sys.stderr)
        return 1

    cfg = json.loads(CONFIG.read_text(encoding="utf-8"))
    langs = cfg.get("languages") or []
    if not langs:
        print("error: no languages in config", file=sys.stderr)
        return 1

    langs = sorted(langs, key=lambda r: (r.get("hue") or 0.0, r.get("name", "")))

    width = max(20, args.width)
    rows = []
    for start in range(0, len(langs), width):
        chunk = langs[start:start + width]
        # Glyph index is derived from the language's own hue bucket, not from its
        # position. The first version cycled the set by position, which produced
        # eight visually identical rows -- each row started at the same glyph and
        # repeated with the same period, so the file looked like a texture rather
        # than a spectrum. Tying the glyph to hue makes adjacent characters differ
        # exactly where the colour differs.
        art = "".join(
            GLYPHS[int((r.get("hue") or 0.0) / 360.0 * len(GLYPHS)) % len(GLYPHS)]
            for r in chunk
        )
        rows.append(art)

    # A legend of hue bands makes the ordering legible as a fact, not a vibe.
    bands = []
    n_bands = 24
    for i in range(n_bands):
        hue = i * 360.0 / n_bands
        rgb = hue_to_rgb(hue, 0.85, 1.0)
        bands.append(f"{hue:5.0f}deg  #{rgb[0]:02x}{rgb[1]:02x}{rgb[2]:02x}")

    lines = [
        "RAiNBOW_Hello-World -- 694 core languages, one character each, hue order",
        f"generated by scripts/render_ascii_bar.py from config/rainbow_langs.json",
        "",
        "Core layer (every Linguist-coloured, detectable language):",
        "",
    ]
    lines.extend(rows)
    lines += [
        "",
        f"{len(langs)} languages, {width} columns per row.",
        "Each character is one language; the row order follows the hue of its",
        "Linguist colour, so reading left to right is a trip through the spectrum.",
        "",
        "Hue reference:",
    ]
    for i in range(0, n_bands, 4):
        lines.append("  " + "   ".join(bands[i:i + 4]))

    text = "\n".join(lines) + "\n"
    if "\ufffd" in text:
        # Would mean a language name round-tripped through the wrong encoding.
        raise SystemExit("refusing to write: output contains U+FFFD")
    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {out} ({out.stat().st_size} bytes, "
          f"{len(langs)} languages, {len(rows)} rows)")
    return 0


if __name__ == "__main__":
    sys.exit(main())